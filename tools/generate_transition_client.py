"""Produce the native crossing and finder tables from the AP catalogs."""
from pathlib import Path
import json,re
ROOT=Path(__file__).resolve().parents[1]

def generate():
    entries=[e for f in ('SceneTransitionCatalog.json','DungeonDoorCatalog.json')
             for e in json.loads((ROOT/'archipelago/soh_extreme'/f).read_text())]
    table=[];finder=[]
    shared={'KAK_WINDMILL':'KAKARIKO_VILLAGE', 'KAK_WINDMILL_LOWER':'KAKARIKO_VILLAGE', 'KAK_WINDMILL_UPPER':'KAKARIKO_VILLAGE',
            'GRAVEYARD_DAMPES_GRAVE':'GRAVEYARD', 'GRAVEYARD_DAMPES_GRAVE_START':'GRAVEYARD',
            'KAK_BAZAAR':'KAKARIKO_VILLAGE','MARKET_BAZAAR':'MARKET',
            'KAK_SHOOTING_GALLERY':'KAKARIKO_VILLAGE','MARKET_SHOOTING_GALLERY':'MARKET',
            'DMT_GREAT_FAIRY_FOUNTAIN':'DEATH_MOUNTAIN_TRAIL',
            'DMC_GREAT_FAIRY_FOUNTAIN':'DEATH_MOUNTAIN_CRATER',
            'OGC_GREAT_FAIRY_FOUNTAIN':'HYRULE_CASTLE',
            'HC_GREAT_FAIRY_FOUNTAIN':'HYRULE_CASTLE',
            'ZF_GREAT_FAIRY_FOUNTAIN':'ZORAS_FOUNTAIN',
            'COLOSSUS_GREAT_FAIRY_FOUNTAIN':'DESERT_COLOSSUS'}
    for e in entries:
        mode={'entrance':'Entrance','grotto_load':'GrottoLoad','grotto_exit':'GrottoExit','door':'Door'}[e['mode']]
        for entrance in e['entrances'] or [-1]:
            pos=e.get('position',[0,0,0])
            table.append(f"    {{ {e['id']}LL, CrossingKind::{mode}, {e['source_scene']}, {e['target_scene']}, {entrance}, {e['content']}, {e.get('door',-1)}, {e.get('room_from',-1)}, {e.get('room_to',-1)}, {e.get('side',-1)}, {pos[0]}.0f, {pos[2]}.0f }},")
        area='RCAREA_'+shared.get(e['source'],'INVALID')
        grotto=e['grotto'] if e['mode']=='grotto_exit' else -1
        finder.append(f"    {{ {e['id']}LL, {e['source_scene']}, {area}, {grotto} }},")
    out=ROOT/'soh/Network/Archipelago'
    for name,rows in [('SceneTransitionData.inc',table),('SceneTransitionScenes.inc',finder)]:
        (out/name).write_text('// Generated by tools/generate_transition_client.py.\n'+'\n'.join(rows)+'\n')
    print('Generated native metadata for',len(entries),'crossings')

if __name__=='__main__':generate()
