"""Build display-only scene transition metadata for the Room debug popup."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]

def generate():
    rows = []
    entries = json.loads((ROOT/'archipelago/soh_extreme/SceneTransitionCatalog.json').read_text())
    for e in entries:
        index = (0x800 if e['mode']=='grotto_exit' else 0x700)+e['grotto'] if e['mode'].startswith('grotto_') else e['entrances'][0]
        grotto = e['grotto'] if e['mode']=='grotto_exit' else -1
        name = json.dumps(e['name'].removeprefix('Scene Transition: '))
        rows.append(f"    {{ {e['id']}LL, {e['source_scene']}, {e['target_scene']}, {index}, {grotto}, {name}, {json.dumps(e['kind'])} }},")
    (ROOT/'soh/Enhancements/randomizer/RoomDebugSceneData.inc').write_text(
        '// Generated by tools/generate_room_debug_scenes.py. Display only.\n'+'\n'.join(rows)+'\n', newline='\n')
    print(f'Generated {len(rows)} scene transitions for Room debug')

if __name__=='__main__': generate()
