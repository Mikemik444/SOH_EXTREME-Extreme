"""Generate display-only Check Finder scene metadata from the native catalogues.

Run after adding checks, grottos, or conversation routes. No AP IDs or rules change.
"""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
NATIVE = ROOT / "soh/Enhancements/randomizer"
OUTPUT = ROOT / "soh/Network/Archipelago"


def catalogues():
    regions, parents, checks = {}, {}, {}
    for path in sorted((NATIVE / "location_access").rglob("*.cpp")):
        text = path.read_text(encoding="utf-8")
        starts = list(re.finditer(r'areaTable\[(RR_\w+)\]\s*=\s*Region\("([^"]+)",\s*(SCENE_\w+)', text))
        for i, match in enumerate(starts):
            region, label, scene = match.groups()
            regions[region] = (label, scene)
            body = text[match.end():starts[i + 1].start() if i + 1 < len(starts) else len(text)]
            for rc in re.findall(r'\bLOCATION\((RC_\w+)', body):
                parents.setdefault(rc, set()).add(region)
    for path in sorted(NATIVE.glob("*.cpp")):
        text = path.read_text(encoding="utf-8")
        for rc, body in re.findall(r'locationTable\[(RC_\w+)\]\s*=\s*(.*?);', text, re.S):
            scene = re.search(r'\bSCENE_\w+', body)
            if scene:
                checks[rc] = scene[0]
    entrances = (NATIVE / "entrance.cpp").read_text(encoding="utf-8")
    grottos = dict(re.findall(r'(RR_\w+),\s*ENTRANCE_GROTTO_LOAD\((GROTTO_\w+)\)', entrances))
    for subregion, parent in {
        "RR_HC_STORMS_GROTTO_BEHIND_WALLS": "RR_HC_STORMS_GROTTO",
        "RR_HF_COW_GROTTO_BEHIND_WEBS": "RR_HF_COW_GROTTO",
    }.items():
        grottos[subregion] = grottos[parent]
    return regions, parents, checks, grottos


def generate():
    regions, parents, checks, grottos = catalogues()
    header = "// Generated by tools/generate_finder_scenes.py; display metadata only.\n"
    overrides = []
    for rc, scene in sorted(checks.items()):
        if scene in ("SCENE_GROTTOS", "SCENE_FAIRYS_FOUNTAIN"):
            ids = {grottos[r] for r in parents.get(rc, ()) if r in grottos}
            if len(ids) != 1:
                raise ValueError(f"Ambiguous grotto for {rc}: {ids}")
            overrides.append(f"    {{ {rc}, {scene}, {ids.pop()} }},")
        elif scene == "SCENE_ID_MAX":
            scenes = {regions[r][1] for r in parents.get(rc, ())} - {"SCENE_ID_MAX"}
            if len(scenes) == 1:
                overrides.append(f"    {{ {rc}, {scenes.pop()}, -1 }},")

    # AP route names predate the fork's native region renames. These are exact
    # aliases, not guesses from a check's name or AP parent region.
    aliases = {
        "LOST_WOODS": "THE_LOST_WOODS", "MARKET": "THE_MARKET",
        "KAK_POTION_SHOP_FRONT": "KAK_POTION_SHOP",
        "KAK_WINDMILL": "KAK_WINDMILL_LOWER",
    }
    scene_aliases = {
        "KAK_GRANNYS_POTION_SHOP": "SCENE_POTION_SHOP_GRANNY",
        "LH_FISHING_HOLE": "SCENE_FISHING_POND",
        "GERUDO_FORTRESS_OUTSKIRTS": "SCENE_GERUDOS_FORTRESS",
        "HYRULE_CASTLE_GROUNDS": "SCENE_HYRULE_CASTLE",
        "JABU_JABUS_BELLY_MAIN": "SCENE_JABU_JABU",
        "SPIRIT_TEMPLE_CHILD": "SCENE_SPIRIT_TEMPLE",
        **{r: "SCENE_FIRE_TEMPLE" for r in (
            "FIRE_TEMPLE_BIG_LAVA_ROOM_NORTH_GORON", "FIRE_TEMPLE_BIG_LAVA_ROOM_SOUTH_GORON",
            "FIRE_TEMPLE_LOOP_GORON_ROOM", "FIRE_TEMPLE_WEST_PEAK",
            "FIRE_TEMPLE_BOULDER_MAZE_LOWER_SIDE_ROOM")},
    }
    shared_areas = {
        "KAK_BAZAAR": "KAKARIKO_VILLAGE", "MARKET_BAZAAR": "MARKET",
        "KAK_SHOOTING_GALLERY": "KAKARIKO_VILLAGE", "MARKET_SHOOTING_GALLERY": "MARKET",
    }
    rows = []
    catalog = json.loads((ROOT / "archipelago/soh_extreme/NpcSpeechCatalog.json").read_text(encoding="utf-8"))
    for entry in catalog:
        if entry.get("native_rc"):
            # Scrub conversations use the same exact scene/instance as the scrub.
            rows.append(f'    {{ {entry["id"]}LL, {entry["native_rc"]}, SCENE_ID_MAX, RCAREA_INVALID, -1, -1, -1 }},')
            continue
        for route in entry["routes"]:
            r = route["region"]
            region = "RR_" + aliases.get(r, r)
            scene = scene_aliases[r] if r in scene_aliases else regions[region][1]
            age = {"child": 0, "adult": 1, "either": -1}[route["age"]]
            time = {"day": 0, "night": 1, "either": -1}[route["time"]]
            area = "RCAREA_" + shared_areas.get(r, "INVALID")
            grotto = grottos.get(region, "-1")
            variants = [scene]
            if scene in ("SCENE_MARKET_DAY", "SCENE_BACK_ALLEY_DAY", "SCENE_MARKET_ENTRANCE_DAY"):
                variants = [scene.replace("_DAY", "_NIGHT")] if time == 1 else [scene]
                if time == -1:
                    variants.append(scene.replace("_DAY", "_NIGHT"))
            for variant in variants:
                rows.append(f'    {{ {entry["id"]}LL, RC_UNKNOWN_CHECK, {variant}, {area}, {grotto}, {age}, {time} }},')
    return {
        "FinderSceneOverrides.inc": header + "\n".join(overrides) + "\n",
        "NpcSpeechScenes.inc": header + "\n".join(dict.fromkeys(rows)) + "\n",
    }


if __name__ == "__main__":
    for name, text in generate().items():
        (OUTPUT / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"Generated {name}: {len(text.splitlines()) - 1} entries")
